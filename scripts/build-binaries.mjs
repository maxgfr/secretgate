#!/usr/bin/env node
// Compile the CLI into standalone executables (`bun build --compile`): no Node
// on the machine, one file per platform. Homebrew installs these as
// `secretgate`; `secretgate init` then pins a copy under ~/.secretgate/bin so the
// hooks survive `brew upgrade` / `brew cleanup`.
//
// Needs Bun on PATH, macOS for the macOS targets (codesign), and a prior
// `pnpm run build`: the OpenCode plugin bundle
// (scripts/secretgate-opencode.mjs) has no file to be copied from inside a
// binary, so its text is embedded through a generated entry under build/.
//
//   node scripts/build-binaries.mjs            all four release targets
//   node scripts/build-binaries.mjs --native   only this machine's target (CI, dev)
//
// Output: dist/secretgate-<platform>-<arch> (the tap's naming) + dist/SHA256SUMS.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const buildDir = join(root, "build");
const distDir = join(root, "dist");

// x64 builds use Bun's baseline (pre-AVX2) runtime: a hook binary that dies with
// SIGILL on an older CPU emits nothing, and an empty hook answer is fail-open.
const TARGETS = [
  { name: "macos-arm64", bun: "bun-darwin-arm64", os: "darwin", arch: "arm64" },
  { name: "macos-x64", bun: "bun-darwin-x64-baseline", os: "darwin", arch: "x64" },
  { name: "linux-arm64", bun: "bun-linux-arm64", os: "linux", arch: "arm64" },
  { name: "linux-x64", bun: "bun-linux-x64-baseline", os: "linux", arch: "x64" },
];

const native = process.argv.includes("--native");
const targets = native ? TARGETS.filter((t) => t.os === process.platform && t.arch === process.arch) : TARGETS;
if (targets.length === 0) {
  console.error(`build-binaries: no target for ${process.platform}-${process.arch}`);
  process.exit(1);
}
if (process.platform !== "darwin" && targets.some((t) => t.os === "darwin")) {
  console.error("build-binaries: the macOS targets must be built on macOS (they are re-signed with codesign) — use --native elsewhere");
  process.exit(1);
}

const pluginPath = join(root, "scripts", "secretgate-opencode.mjs");
if (!existsSync(pluginPath)) {
  console.error("build-binaries: scripts/secretgate-opencode.mjs is missing — run `pnpm run build` first");
  process.exit(1);
}

mkdirSync(buildDir, { recursive: true });
const entry = join(buildDir, "secretgate-bin.ts");
writeFileSync(
  entry,
  `// Generated by scripts/build-binaries.mjs — do not edit.
import { run, setEmbeddedOpencodePlugin } from "../src/cli.ts";

setEmbeddedOpencodePlugin(${JSON.stringify(readFileSync(pluginPath, "utf8"))});
run(process.argv.slice(2), {
  stdout: (s) => process.stdout.write(s),
  stderr: (s) => process.stderr.write(s),
}).then((code) => {
  process.exitCode = code;
});
`,
);

rmSync(distDir, { recursive: true, force: true });
mkdirSync(distDir, { recursive: true });
const sums = [];
for (const t of targets) {
  const file = `secretgate-${t.name}`;
  const outfile = join(distDir, file);
  // Run from build/: `bun build --compile` leaves `.<hash>.bun-build` temp
  // files in its working directory, and build/ is removed below.
  execFileSync("bun", ["build", "--compile", "--minify", `--target=${t.bun}`, entry, "--outfile", outfile], { cwd: buildDir, stdio: "inherit" });
  // Bun appends the program to a copy of its own runtime. For darwin-x64 that
  // leaves Oven's hardened-runtime signature in place but no longer matching
  // the file, and macOS kills a binary whose signature is invalid. Re-sign
  // every macOS output ad hoc, then verify.
  if (t.os === "darwin") {
    execFileSync("codesign", ["--force", "--sign", "-", outfile], { stdio: "inherit" });
    execFileSync("codesign", ["--verify", "--strict", outfile], { stdio: "inherit" });
  }
  sums.push(`${createHash("sha256").update(readFileSync(outfile)).digest("hex")}  ${file}`);
}
writeFileSync(join(distDir, "SHA256SUMS"), `${sums.join("\n")}\n`);
rmSync(buildDir, { recursive: true, force: true });
console.log(`build-binaries: ${targets.map((t) => `secretgate-${t.name}`).join(", ")} -> dist/`);
